VAGUE_PURPOSES = {"", "прочее", "оплата", "перевод", "без ндс", "оплата без ндс"}


def categorize_rule(operation: dict | object) -> dict[str, object]:
    """Classify a single operation and return an explanation and confidence."""
    get = operation.get if isinstance(operation, dict) else lambda key, default="": getattr(operation, key, default)
    purpose = " ".join(
        str(get("purpose", "")).strip().lower().replace("ё", "е").replace("без ндс", " ").split()
    )
    counterparty = str(get("counterparty", "")).strip().lower().replace("ё", "е")
    inn = str(get("inn", "")).strip().lower().replace("ё", "е")
    text = " ".join(part for part in ("" if purpose in VAGUE_PURPOSES else purpose, counterparty, inn) if part)
    amount = float(get("amount", 0) or 0)
    category, confidence = "", 0.0
    for candidate, words in RULES:
        if candidate == "Выручка и поступления от клиентов" and amount <= 0:
            continue
        if candidate != "Переводы между собственными счетами" and candidate != "Выручка и поступления от клиентов" and amount >= 0:
            continue
        if any(word in text for word in words):
            category, confidence = candidate, 0.9 if candidate == "Выручка и поступления от клиентов" else 0.85
            break
    if not category:
        confidence = 0.5
    needs_review = confidence < 0.65
    if needs_review:
        category = "Требует проверки"
    return {"category": category, "method": "правила", "confidence": confidence, "needs_review": needs_review}


